// setup.js — one-time Stellar testnet account setup for BOUNTEA.
//
// Automates the shared testnet setup (keypairs, XLM funding, USDC trustlines)
// and writes a starter .env. The remaining manual steps (Circle USDC faucet
// captcha) are printed at the end.
//
// Run:  cd backend && npm install && npm run setup

import fs from "fs/promises";
import {
  Keypair,
  Horizon,
  Networks,
  TransactionBuilder,
  Operation,
  Asset,
  BASE_FEE,
} from "@stellar/stellar-sdk";

const USDC_ISSUER = "GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5";
const horizon = new Horizon.Server("https://horizon-testnet.stellar.org");

async function friendbot(addr) {
  const res = await fetch(`https://friendbot.stellar.org?addr=${encodeURIComponent(addr)}`);
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`friendbot failed for ${addr}: ${res.status} ${text}`);
  }
  return res.json();
}

async function addTrustline(kp) {
  // Retry a few times in case Horizon hasn't indexed the funded account yet.
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const acc = await horizon.loadAccount(kp.publicKey());
      const tx = new TransactionBuilder(acc, {
        fee: BASE_FEE,
        networkPassphrase: Networks.TESTNET,
      })
        .addOperation(Operation.changeTrust({ asset: new Asset("USDC", USDC_ISSUER) }))
        .setTimeout(60)
        .build();
      tx.sign(kp);
      return await horizon.submitTransaction(tx);
    } catch (err) {
      if (attempt === 4) throw err;
      await new Promise((r) => setTimeout(r, 2000));
    }
  }
}

async function main() {
  console.log("Generating two Stellar testnet keypairs...");
  const recipient = Keypair.random(); // worker / payTo (receives USDC)
  const payer = Keypair.random();    // client agent (signs & pays)

  console.log("Funding both accounts with testnet XLM (friendbot)...");
  await Promise.all([friendbot(recipient.publicKey()), friendbot(payer.publicKey())]);
  await new Promise((r) => setTimeout(r, 3000));

  console.log("Adding USDC trustlines to both accounts...");
  await Promise.all([addTrustline(recipient), addTrustline(payer)]);

  const env = `# BOUNTEA backend — generated by setup.js
# Facilitator: x402.org (testnet only, no API key required)
STELLAR_NETWORK=stellar:testnet
FACILITATOR_URL=https://x402.org/facilitator

# Worker / recipient (receives USDC; needs USDC trustline — done above)
STELLAR_RECIPIENT=${recipient.publicKey()}
STELLAR_RECIPIENT_SECRET=${recipient.secret()}

# Client agent / payer (signs & pays; needs USDC balance from Circle faucet)
STELLAR_SECRET_KEY=${payer.secret()}
STELLAR_PAYER_PUBLIC=${payer.publicKey()}

# Neema's spending cap (max USDC per task). Task prices must stay <= this.
SPENDING_CAP_USDC=12
`;
  await fs.writeFile(".env", env);

  console.log("\n✅ Setup complete. .env written.\n");
  console.log("Manual steps remaining (web, Captcha):");
  console.log(`1) Fund the PAYER with testnet USDC:`);
  console.log(`   https://faucet.circle.com  →  select "Stellar testnet"  →  paste:`);
  console.log(`   ${payer.publicKey()}`);
  console.log(`   (recipient already has a trustline; no USDC needed there for the demo)\n`);
  console.log("2) (Optional) If you later switch to OZ Channels facilitator, get an API key at");
  console.log("   https://channels.openzeppelin.com/testnet/gen and set OZ_API_KEY + FACILITATOR_URL.\n");
  console.log("Secrets saved in backend/.env (gitignored). Keep them safe.");
  console.log("\nNext: npm run dev  (starts the x402 seller on http://localhost:4021)");
}

main().catch((err) => {
  console.error("Setup failed:", err);
  process.exit(1);
});